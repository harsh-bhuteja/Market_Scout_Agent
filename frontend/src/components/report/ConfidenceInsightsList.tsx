import React, { useState } from 'react';
import { MarketBrief } from '../../types';
import { getConfidenceBadgeProps } from '../../utils/formatters';
import { ShieldCheck, ChevronDown, ChevronUp, Link as LinkIcon } from 'lucide-react';

export const ConfidenceInsightsList: React.FC<{ brief: MarketBrief }> = ({ brief }) => {
  const [expandedId, setExpandedId] = useState<string | null>(null);

  const toggleExpand = (id: string) => {
    setExpandedId(expandedId === id ? null : id);
  };

  return (
    <div className="glass-panel rounded-2xl p-6 border border-white/[0.08] space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <ShieldCheck className="w-5 h-5 text-white" />
          <h3 className="text-sm font-bold text-white uppercase tracking-wider">
            Evidence-Backed Confidence Insights
          </h3>
        </div>

        {/* Legend */}
        <div className="flex items-center gap-3 text-xs font-mono">
          <span className="flex items-center gap-1.5 text-white">
            <span className="w-2 h-2 rounded-full bg-white shadow-[0_0_6px_#ffffff]" />
            High (&gt;60% evidence)
          </span>
          <span className="flex items-center gap-1.5 text-zinc-300">
            <span className="w-2 h-2 rounded-full bg-zinc-400" />
            Medium (20-60%)
          </span>
          <span className="flex items-center gap-1.5 text-zinc-400">
            <span className="w-2 h-2 rounded-full bg-zinc-600" />
            Low (&lt;20%)
          </span>
        </div>
      </div>

      <p className="text-xs text-zinc-400">
        Every analytical claim generated by Market Scout Agent is validated against raw job posting records with transparent confidence scoring.
      </p>

      <div className="space-y-3 pt-2">
        {brief.confidenceInsights.map((insight) => {
          const badge = getConfidenceBadgeProps(insight.confidence);
          const isExpanded = expandedId === insight.id;

          return (
            <div
              key={insight.id}
              className={`p-4 rounded-xl border transition-all ${badge.bg} ${badge.border} shadow-gloss-reflection`}
            >
              <div
                className="flex items-start justify-between gap-4 cursor-pointer"
                onClick={() => toggleExpand(insight.id)}
              >
                <div className="space-y-1">
                  <div className="flex items-center gap-2">
                    <span
                      className={`inline-flex items-center gap-1.5 px-2 py-0.5 rounded text-[11px] font-mono font-bold border ${badge.color} ${badge.border}`}
                    >
                      <span className={`w-1.5 h-1.5 rounded-full ${badge.dot}`} />
                      {insight.confidence.toUpperCase()} CONFIDENCE
                    </span>
                    <span className="text-[11px] font-mono text-zinc-400">
                      [{insight.category}]
                    </span>
                  </div>

                  <h4 className="text-sm font-semibold text-white leading-snug pt-1">
                    {insight.claim}
                  </h4>
                </div>

                <button
                  type="button"
                  className="p-1 rounded text-zinc-400 hover:text-white shrink-0"
                >
                  {isExpanded ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
                </button>
              </div>

              {/* Rationale & Posting Citation Details */}
              <div className="mt-3 pt-3 border-t border-white/[0.06] space-y-2">
                <div className="flex flex-wrap items-center justify-between text-xs text-zinc-300">
                  <span>
                    <strong>Evidence Base:</strong> {insight.evidencePostingCount} postings ({insight.evidencePercentage}% of sample)
                  </span>
                  <span className="text-[11px] font-mono text-zinc-400">
                    Confidence Index: {insight.confidenceScore}/100
                  </span>
                </div>

                <p className="text-xs text-zinc-300 italic">
                  "{insight.confidenceRationale}"
                </p>

                {isExpanded && (
                  <div className="pt-2">
                    <span className="text-[11px] font-mono text-zinc-400 block mb-1">
                      Cited Sample Posting Record IDs:
                    </span>
                    <div className="flex flex-wrap gap-1.5">
                      {insight.samplePostingIds.map((pid) => (
                        <span
                          key={pid}
                          className="px-2 py-0.5 rounded bg-black text-[10px] font-mono text-white border border-white/20 flex items-center gap-1 shadow-gloss-reflection"
                        >
                          <LinkIcon className="w-2.5 h-2.5" />
                          {pid}
                        </span>
                      ))}
                    </div>
                  </div>
                )}
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
