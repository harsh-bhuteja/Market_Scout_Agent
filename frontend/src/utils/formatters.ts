import { CurrencyCode, ConfidenceLevel, HiringOutlookVerdict, MarketBrief } from '../types';

export function formatCurrency(amount: number, currency: CurrencyCode = 'USD'): string {
  const symbols: Record<CurrencyCode, string> = {
    USD: '$',
    EUR: '€',
    GBP: '£',
    INR: '₹',
  };

  const symbol = symbols[currency] || '$';

  if (currency === 'INR') {
    if (amount >= 10000000) {
      return `${symbol}${(amount / 10000000).toFixed(2)} Cr`;
    }
    if (amount >= 100000) {
      return `${symbol}${(amount / 100000).toFixed(1)} L`;
    }
    return `${symbol}${amount.toLocaleString('en-IN')}`;
  }

  if (amount >= 1000000) {
    return `${symbol}${(amount / 1000000).toFixed(1)}M`;
  }
  if (amount >= 1000) {
    return `${symbol}${(amount / 1000).toFixed(0)}k`;
  }
  return `${symbol}${amount.toLocaleString('en-US')}`;
}

export function formatFullCurrency(amount: number, currency: CurrencyCode = 'USD'): string {
  const symbols: Record<CurrencyCode, string> = {
    USD: '$',
    EUR: '€',
    GBP: '£',
    INR: '₹',
  };
  const symbol = symbols[currency] || '$';
  return `${symbol}${Math.round(amount).toLocaleString()}`;
}

export function formatPercent(value: number): string {
  return `${Math.round(value)}%`;
}

// Monochrome Confidence Badge Styling
export function getConfidenceBadgeProps(level: ConfidenceLevel): {
  color: string;
  bg: string;
  border: string;
  dot: string;
} {
  switch (level) {
    case 'High':
      return {
        color: 'text-white font-semibold',
        bg: 'bg-white/[0.08]',
        border: 'border-white/30',
        dot: 'bg-white shadow-[0_0_8px_#ffffff]',
      };
    case 'Medium':
      return {
        color: 'text-zinc-300',
        bg: 'bg-white/[0.04]',
        border: 'border-white/15',
        dot: 'bg-zinc-400 shadow-[0_0_8px_#a1a1aa]',
      };
    case 'Low':
      return {
        color: 'text-zinc-400',
        bg: 'bg-white/[0.02]',
        border: 'border-white/10',
        dot: 'bg-zinc-600',
      };
  }
}

